"""Build a RAM-only USB probe using the upstream loader's transport code.

No kernel, payload access, block I/O or storage command implementation is linked.
"""
from pathlib import Path
import hashlib
import json
import shutil
import struct
import subprocess

root=Path(__file__).resolve().parents[1]
upstream=root/'hackios/xnuloader'
out=root/'out/lmi-usb-probe'
out.mkdir(parents=True,exist_ok=True)
s=(upstream/'loader.c').read_text()
helpers=s[s.index('static efi_system_table *ST;'):s.index('/*\n * Write back and drop cached copies')]
transport=s[s.index('#define USB_EP_OUT'):s.index('/*\n * One command from the host.')]
transport=transport.replace('static int download_to_ramdisk;     /* set by "oem ramdisk" for the one download that follows */','')
transport=transport.replace('if (running_live != NULL && READ_SYSREG(CNTVCT_EL0) - began > 3 * freq)',
                            'if (READ_SYSREG(CNTVCT_EL0) - began > 3 * freq)')
transport=transport.replace('wdt_pet();','probe_deadline();')
loop=s[s.index('static void\nusb_command_loop(void)'):s.index('/* ------------------------------------------------------------------------ */',s.index('static void\nusb_command_loop(void)'))]
loop=loop.replace('for (;;) {','for (;;) {\n\t\tprobe_deadline();',1)
deadline='''
static uint64_t probe_started;
static void probe_deadline(void) {
    if (READ_SYSREG(CNTVCT_EL0) - probe_started >= 90 * READ_SYSREG(CNTFRQ_EL0)) {
        ST->rt->reset_system(0, 0, 0, NULL);
        for (;;) {}
    }
}
'''
commands='''
static void fb_command(char *cmd) {
    print("host: %s\\n", cmd);
    if (str_eq(cmd,"getvar:product")) fb_reply("OKAY","lmi-hackios-usb-probe");
    else if (str_eq(cmd,"getvar:version")) fb_reply("OKAY","0.4");
    else if (str_eq(cmd,"getvar:serialno")) fb_reply("OKAY","xnuloader");
    else if (str_eq(cmd,"getvar:unlocked")) fb_reply("OKAY","yes");
    else if (str_eq(cmd,"getvar:mode")) fb_reply("OKAY","RAM-only diagnostic");
    else if (str_eq(cmd,"getvar:all")) {
        fb_reply("INFO","product: lmi-hackios-usb-probe");
        fb_reply("INFO","mode: RAM-only diagnostic");
        fb_reply("OKAY","");
    } else if (str_eq(cmd,"oem log")) fb_reply("OKAY","");
    else if (str_eq(cmd,"upload")) {
        uint64_t n=log_len;
        fb_reply_data(n);
        usb_tx((const uint8_t *)log_buf,n);
        fb_reply("OKAY","");
    } else if (str_eq(cmd,"reboot") || str_eq(cmd,"oem reboot")) {
        fb_reply("OKAY",""); BS->stall(200000);
        ST->rt->reset_system(0,0,0,NULL);
    } else fb_reply("FAIL","diagnostic: command unavailable");
}
'''
entry='''
efi_status EFIAPI efi_main(efi_handle image,efi_system_table *st) {
    static const efi_guid guid=EFI_GOP_GUID;
    efi_gop *gop=NULL;
    ST=st; BS=st->bs; IMAGE=image;
    BS->set_watchdog_timer(0,0,0,NULL);
    probe_started=READ_SYSREG(CNTVCT_EL0);
    print("lmi USB probe: upstream transport, no XNU or storage writes\\n");
    print("EL=%x MMFR0=%x\\n",READ_SYSREG(CurrentEL)>>2,READ_SYSREG(ID_AA64MMFR0_EL1));
    if (!EFI_ERROR(BS->locate_protocol(&guid,NULL,(void **)&gop)) && gop->mode && gop->mode->info)
        print("GOP fb=%x width=%d height=%d stride=%d\\n",gop->mode->fb_base,
          (uint64_t)gop->mode->info->width,(uint64_t)gop->mode->info->height,
          (uint64_t)gop->mode->info->pixels_per_scanline);
    print("USB probe returns to Android after 90 seconds.\\n");
    if (usb_start()) usb_command_loop();
    print("USB start failed; resetting in 10 seconds.\\n"); BS->stall(10000000);
    ST->rt->reset_system(0,0,0,NULL);
    return 0;
}
'''
source='/* Derived from xnuloader/loader.c; transport-only lmi diagnostic. */\n#include "efi.h"\n'+helpers+deadline+transport+commands+loop+entry
assert not any(x in source for x in ('write_blocks','read_blocks','PAYLOAD_BASE','run_kernel','find_log_partition','block_poll'))
(out/'probe.c').write_text(source)
shutil.copy2(upstream/'efi.h',out/'efi.h')
flags=['--target=aarch64-unknown-windows','-ffreestanding','-fno-builtin','-fno-stack-protector','-fshort-wchar','-mgeneral-regs-only','-O1','-Wall','-Wextra','-Wno-unused-parameter','-Wno-unused-function']
subprocess.run(['clang',*flags,'-c',str(out/'probe.c'),'-o',str(out/'probe.obj')],check=True)
subprocess.run(['lld-link','/subsystem:efi_application','/entry:efi_main','/nodefaultlib','/base:0xA1000000',f'/out:{out}/probe.efi',str(out/'probe.obj')],check=True)
b=(out/'probe.efi').read_bytes(); pe=struct.unpack_from('<I',b,60)[0]
assert b[:2]==b'MZ' and b[pe:pe+4]==b'PE\0\0' and struct.unpack_from('<H',b,pe+4)[0]==0xaa64
assert struct.unpack_from('<H',b,pe+24+68)[0]==10
header='/* Generated by build-lmi-usb-probe.py */\nSTATIC CONST UINT8 mLmiUsbProbe[] = {\n'
for i in range(0,len(b),24):header+=','.join(f'0x{x:02x}' for x in b[i:i+24])+',\n'
header+='};\n'
(out/'LmiUsbProbe.h').write_text(header)
wrapper=(root/'port-drafts/uefi/XnuLoader-lmi-diagnostics.c').read_text()
wrapper=wrapper.replace('#include "XnuLoader.h"','#include "XnuLoader.h"\n#include "LmiUsbProbe.h"')
marker='  Print (L"Diagnostics only. Returning to Android in 30 seconds.\\r\\n");'
assert marker in wrapper
launch='''  {
    EFI_HANDLE Handle = NULL;
    Print (L"Starting RAM-only USB probe; 90-second timeout.\\r\\n");
    Status = gBS->LoadImage (FALSE, gImageHandle, NULL,
                            (VOID *)mLmiUsbProbe, sizeof (mLmiUsbProbe), &Handle);
    Print (L"USB probe LoadImage: %r\\r\\n", Status);
    if (!EFI_ERROR (Status)) {
      Status = gBS->StartImage (Handle, NULL, NULL);
      Print (L"USB probe returned: %r\\r\\n", Status);
      gBS->UnloadImage (Handle);
    }
  }
'''
wrapper=wrapper.replace(marker,launch+marker)
(out/'XnuLoader-lmi-usb-probe.c').write_text(wrapper)
report=dict(bytes=len(b),sha256=hashlib.sha256(b).hexdigest(),upstream_loader_sha256=hashlib.sha256(s.encode()).hexdigest(),storage_io_linked=False,xnu_launch=False,payload_addresses=False,reset_after_seconds=90,commands=['getvar','oem log','upload','reboot'],hardware_tested=False)
(out/'manifest.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
